std::string run_row_json(const fs::path& unit, const fs::path& cdb, bool model_only, const Config& cfg_in) {
    // The unit's `main` only: PRISM_PIR_ONLY is the stage's own per-function filter ("<unit file>\t<function>").
    // (It also makes the stage leave with exit 75 when its memory watchdog gives up: the parent reports that as UNKNOWN.)
    const std::string only = unit.filename().string() + "\tmain\n";
    // The variables are this call's: put back what the process had when it returns (the stage re-reads
    // PRISM_PIR_ONLY whenever it changes, so a leftover selection would hide every later unit's functions)
    struct EnvRestore {
        std::vector<std::pair<std::string, std::optional<std::string>>> saved;
        void set(const char* k, const std::string& v, bool overwrite) {
            const char* old = std::getenv(k);
            saved.emplace_back(k, old ? std::optional<std::string>(old) : std::nullopt);
            if (old && !overwrite) return;
#ifdef _WIN32
            _putenv_s(k, v.c_str());
#else
            setenv(k, v.c_str(), 1);
#endif
        }
        ~EnvRestore() {
            for (auto it = saved.rbegin(); it != saved.rend(); ++it) {
#ifdef _WIN32
                _putenv_s(it->first.c_str(), it->second ? it->second->c_str() : "");
#else
                if (it->second) setenv(it->first.c_str(), it->second->c_str(), 1);
                else unsetenv(it->first.c_str());
#endif
            }
        }
    } env_restore;
    env_restore.set("PRISM_PIR_ONLY", only, true);
    env_restore.set("PRISM_PIR_INLINE_DEPTH", "24", false);
    Config cfg = cfg_in;
    cfg.root = unit.parent_path();
    if (!cdb.empty()) cfg.compile_commands = cdb;
    if (model_only) cfg.pir_only_props = {"model"};
    auto fs_ = pir::run_pir({unit}, cfg);
    nlohmann::json j;
    j["verdict"] = "NOTRUN";
    j["message"] = "no finding for main";
    for (auto& f : fs_) {
        if (f.function && *f.function == "main") {
            j["verdict"] = f.status;
            j["cls"] = f.cls;
            j["message"] = f.message;
            j["cex"] = f.counterexample;
            j["line"] = f.line ? std::to_string(*f.line) : "";
            j["extra"] = f.extra;
            break;
        }
        if (!f.function && (f.status == "NOTRUN" || f.status == "ERROR")) {
            j["verdict"] = f.status;
            j["message"] = f.message;
        }
    }
    return j.dump();
}

std::string generate_harness_body(const Spec& sp, const DevModel* dev, bool no_device, std::uint64_t window,
                                  const std::string& driver_abs, const std::vector<std::string>& extra_abs,
                                  const std::string& driver_text);

Report check_module(const RunOptions& opt, const Config& cfg_in) {
    auto t0 = std::chrono::steady_clock::now();
    Report rep;
    const fs::path specpath = fs::absolute(opt.spec);
    Spec sp = parse_module_spec(read_text(specpath), specpath.string());
    if (opt.steps >= 0) sp.steps = opt.steps;
    if (opt.teardown_ops >= 0) sp.teardown_ops = opt.teardown_ops == 1;
    if (!opt.ops.empty()) {
        std::vector<Op> keep;
        for (auto& o : sp.ops)
            if (std::find(opt.ops.begin(), opt.ops.end(), o.name) != opt.ops.end()) keep.push_back(o);
        if (keep.empty()) throw std::runtime_error("--ops names no operation of the module description");
        sp.ops = keep;
    }
    for (auto& d : opt.defines) sp.defines.push_back(d);
    if (!opt.properties.empty()) sp.properties = opt.properties;
    rep.module = sp.name;

    // device model
    std::optional<DevModel> dev;
    std::string devname = opt.device_override.empty() ? sp.device : opt.device_override;
    if (devname == "none") devname.clear();
    if (!devname.empty()) {
        std::string text;
        if (devname.rfind("builtin:", 0) == 0) text = embedded("device/" + devname.substr(8) + ".pdm");
        else {
            fs::path dp = fs::path(devname).is_absolute() ? fs::path(devname) : specpath.parent_path() / devname;
            text = read_text(dp);
            devname = dp.string();
        }
        dev = parse_device_model(text, devname);
        rep.device = dev->name;
        rep.device_validation = dev->validation;
    }

    // driver source
    fs::path driver = fs::path(sp.driver);
    if (!driver.is_absolute()) {
        // relative: under --kernel-root, else next to the module description
        if (!opt.kernel_root.empty()) driver = opt.kernel_root / driver;
        else if (fs::exists(specpath.parent_path() / driver)) driver = specpath.parent_path() / driver;
        else throw std::runtime_error("the driver path is relative: give --kernel-root");
    }
    std::vector<std::string> extra_abs;
    for (auto& e : sp.extra_sources) extra_abs.push_back((fs::path(e).is_absolute() ? fs::path(e) : (opt.kernel_root.empty() ? specpath.parent_path() : opt.kernel_root) / e).generic_string());
    std::string driver_text = read_text(driver);
    std::string patched_note;
    if (!sp.patches.empty()) {
        for (auto& [o, n] : sp.patches) {
            // every occurrence is replaced; a patch that matches nothing is an error, never a silent no-op
            auto p = driver_text.find(o);
            if (p == std::string::npos) throw std::runtime_error("patch does not apply to " + driver.string() + ": " + o.substr(0, 60));
            while (p != std::string::npos) {
                driver_text.replace(p, o.size(), n);
                p = driver_text.find(o, p + n.size());
            }
        }
        fs::create_directories(fs::absolute(opt.out) / sp.name);
        driver = fs::absolute(opt.out) / sp.name / "driver_patched.c";
        write_text(driver, driver_text);
        patched_note = std::to_string(sp.patches.size()) + " source substitution(s) applied to the driver (an adaptation or a mutant: the unit is NOT the shipped source; see the module description)";
    }
    rep.entry_points = discover_entry_points(driver_text, sp);

    // output directory and embedded headers
    const fs::path outdir = fs::absolute(opt.out) / sp.name;
    fs::create_directories(outdir);
    for (auto& [n, t] : embedded_device_files()) {
        if (n.rfind("device/", 0) != 0) continue;
        auto base = n.substr(7);
        if (base.size() > 4 && base.substr(base.size() - 4) == ".pdm") continue;
        write_text(outdir / base, t);
    }
    const std::string body = generate_harness_body(sp, dev ? &*dev : nullptr, !dev, 0x1000, driver.generic_string(), extra_abs, driver_text);

    // rows
    std::set<std::string> want;
    for (auto& p : sp.properties) want.insert(norm_prop(p));
    const bool all = want.empty();
    auto selected = [&](const std::string& p) { return all || want.count(p) > 0; };
    std::vector<Row> rows;
    {
        Row r;
        r.name = "all";
        for (auto& p : module_props()) if (selected(p)) r.on.insert(p);
        r.what = "every selected module property and every native check (UB, memory errors), events and interrupts on";
        rows.push_back(r);
        Row s = r;
        s.name = "all-sequential";
        s.async = false;
        s.what = "same, with no device events and no interrupts (separates interrupt-dependent failures)";
        rows.push_back(s);
        Row m;
        m.name = "memory";
        m.what = "native checks only (UB and memory errors in every entry point), module checks off";
        rows.push_back(m);
        for (auto& p : module_props()) {
            if (!selected(p)) continue;
            Row q;
            q.name = p;
            q.on = {p};
            q.native = false;
            q.what = "module property '" + p + "' only; native checks not verified in this run";
            rows.push_back(q);
        }
    }
    {
        // coverage rows: is each part of the module reachable under the model? (a PROVED row elsewhere is
        // vacuous for a part nothing can reach)
        auto cov = [&](const std::string& name, int id, const std::string& what) {
            Row c;
            c.name = "cover-" + name;
            c.native = false;
            c.cover = id;
            c.what = "coverage: " + what + " (FAILED here means reachable)";
            rows.push_back(c);
        };
        cov("probe-ok", 1, "probe returns 0");
        cov("probe-fail", 2, "probe fails and the failing-probe path runs");
        cov("irq", 3, "the interrupt handler runs");
        cov("remove", 4, "remove runs");
        if (sp.teardown_ops) cov("teardown-op", 5, "an operation arrives after remove, before devres release");
        for (std::size_t i = 0; i < (sp.steps > 0 ? sp.ops.size() : 0); ++i)   // no operation can run with steps 0
            cov("op-" + sp.ops[i].name, 10 + static_cast<int>(i), "operation " + sp.ops[i].name + " is invoked");
        for (std::size_t i = 0; i < (sp.steps > 0 ? sp.ops.size() : 0); ++i)
            if (sp.ops[i].body.find("PRISM_OP_COVER") != std::string::npos)
                cov("op-" + sp.ops[i].name + "-body", 30 + static_cast<int>(i),
                    "operation " + sp.ops[i].name + " gets past its framework guard to its body");
    }
    if (!opt.rows.empty()) {
        std::vector<Row> keep;
        for (auto& r : rows)
            if (std::find(opt.rows.begin(), opt.rows.end(), r.name) != opt.rows.end() ||
                (r.cover && std::find(opt.rows.begin(), opt.rows.end(), "cover") != opt.rows.end()))
                keep.push_back(r);
        if (keep.empty()) throw std::runtime_error("--rows names no known row");
        rows = keep;
    }

    // units and the compile database
    nlohmann::json cdb = nlohmann::json::array();
    nlohmann::json tmpl;
    bool have_cdb = false;
    if (!opt.cc_like.empty()) {
        auto j = nlohmann::json::parse(read_text(opt.cc_like));
        for (auto& e : j) {
            if (opt.cc_like_file.empty() || e.value("file", "").size() >= opt.cc_like_file.size() &&
                                                 e.value("file", "").compare(e.value("file", "").size() - opt.cc_like_file.size(),
                                                                             opt.cc_like_file.size(), opt.cc_like_file) == 0) {
                tmpl = e;
                have_cdb = true;
                break;
            }
        }
        if (!have_cdb) throw std::runtime_error("no entry in " + opt.cc_like.string() + " matches " + opt.cc_like_file);
    }
    std::vector<fs::path> units;
    for (auto& r : rows) {
        std::ostringstream o;
        o << "/* row '" << r.name << "': " << r.what << " */\n";
        for (auto& p : module_props())
            if (!r.on.count(p)) o << "#define PRISM_OFF_" << p << "\n";
        if (r.async) {
            if (sp.irq_at_api) o << "#define PRISM_IRQ_AT_API\n";
            if (sp.irq_at_mmio) o << "#define PRISM_IRQ_AT_MMIO\n";
        }
        if (r.cover) o << "#define PRISM_COVER " << r.cover << "\n";
        o << "#define PRISM_IRQ_SPURIOUS " << (sp.irq_spurious == "yes" ? 1 : sp.irq_spurious == "no" ? 0 : 2) << "\n";
        if (!r.async) o << "#define PRISM_IRQ_BUDGET 0\n#define PRISM_EVENT_BUDGET 0\n";
        o << body;   // the unit itself must hold main: pir reports the functions defined in the unit file
        auto up = outdir / ("row_" + r.name + ".c");
        write_text(up, o.str());
        units.push_back(up);
        if (have_cdb) cdb.push_back(clone_entry(tmpl, up, outdir));
    }
    rep.unit_path = outdir.string();
    if (have_cdb) {
        rep.cdb_path = (outdir / "compile_commands.json").string();
        write_text(rep.cdb_path, cdb.dump(2));
    }
    if (opt.generate_only) {
        rep.verdict = "NOTRUN";
        rep.notes = "generate-only: unit written, pir not run\n";
        return rep;
    }

    // run every row: in a child process of prism-module (memory and time isolated, peak RSS measured), or in this
    // process when no self_exe is given (tests). The harness nests probe, stubs and handlers: more than depth 4.
    Config cfg = cfg_in;
    cfg.root = outdir;
    if (have_cdb) cfg.compile_commands = rep.cdb_path;
    std::vector<RowResult> results(rows.size());
    auto run_one = [&](std::size_t i) {
        RowResult rr;
        rr.row = rows[i];
        auto t1 = std::chrono::steady_clock::now();
        nlohmann::json j;
        if (opt.self_exe.empty()) {
            try {
                j = nlohmann::json::parse(run_row_json(units[i], have_cdb ? fs::path(rep.cdb_path) : fs::path{}, !rows[i].native, cfg));
            } catch (const std::exception& e) {
                j = {{"verdict", "ERROR"}, {"message", std::string("row failed: ") + e.what()}};
            }
        } else {
            exec::Spec es;
            es.argv = {opt.self_exe.string(), "row", units[i].string(), "--root", outdir.string(), "--timeout", std::to_string(cfg.timeout),
                       "--unwind", std::to_string(cfg.unwind), "--jobs", std::to_string(cfg.jobs)};
            if (have_cdb) { es.argv.push_back("--cdb"); es.argv.push_back(rep.cdb_path); }
            if (!rows[i].native) es.argv.push_back("--model-only");
            es.env_set["PRISM_PIR_INLINE_DEPTH"] = "24";
            if (opt.mem_mb) es.env_set["PRISM_MEM_BUDGET_MB"] = std::to_string(opt.mem_mb);
            es.timeout_ms = static_cast<std::uint64_t>((std::max(300.0, 10.0 * cfg.timeout) + 300.0) * 1000.0);
            auto r = exec::run(es);
            rr.extra["peak_rss_mb"] = std::to_string(r.peak_rss_bytes >> 20);
            std::string line, last;
            std::istringstream in(r.out);
            while (std::getline(in, line)) if (!line.empty() && line[0] == '{') last = line;
            if (!last.empty()) {
                j = nlohmann::json::parse(last, nullptr, false);
                if (j.is_discarded()) j = {{"verdict", "ERROR"}, {"message", "unreadable row result"}};
            } else if (r.timed_out) {
                j = {{"verdict", "TIMEOUT"}, {"message", "the row's process ran past its wall-clock budget"}};
            } else if (r.exit_code == 75) {
                // pir's memory watchdog: the row's process left at once (docs/PIR.md, memory budget); no answer, never a proof
                j = {{"verdict", "UNKNOWN"}, {"message", "memory budget reached in the row's process (exit 75, PRISM_MEM_BUDGET_MB=" +
                                                              (opt.mem_mb ? std::to_string(opt.mem_mb) : std::string("default")) + "): no answer"}};
            } else {
                j = {{"verdict", "ERROR"}, {"message", "row process rc " + std::to_string(r.rc()) + ": " + r.err.substr(0, 200)}};
            }
        }
        rr.verdict = j.value("verdict", "ERROR");
        rr.cls = j.value("cls", "");
        rr.message = j.value("message", "");
        rr.line = j.value("line", "");
        rr.cex = j.value("cex", "");
        if (j.contains("extra") && j["extra"].is_object())
            for (auto it = j["extra"].begin(); it != j["extra"].end(); ++it)
                if (it.value().is_string()) rr.extra[it.key()] = it.value().get<std::string>();
        rr.pir_verdict = rr.verdict;
        rr.seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - t1).count();
        results[i] = std::move(rr);
    };
    {
        const std::size_t nthreads = (opt.self_exe.empty() || opt.row_jobs < 2) ? 1 : static_cast<std::size_t>(std::min(opt.row_jobs, 6));
        std::atomic<std::size_t> next{0};
        std::vector<std::thread> pool;
        for (std::size_t t = 0; t < nthreads; ++t)
            pool.emplace_back([&] {
                for (std::size_t i = next++; i < rows.size(); i = next++) run_one(i);
            });
        for (auto& t : pool) t.join();
    }

    // read the rows back as module properties
    // The module-level verdict: PIR PROVED* on a loop-free harness is a
    // statement about the bounded sequences the harness contains, so it is
    // reported as BOUNDED (docs/DEVICE_MODEL.md section 6); FAILED, UNKNOWN,
    // TIMEOUT, NEEDS-HARNESS, NOTRUN pass through.
    auto module_verdict = [&](const std::string& v) {
        if (v == "PROVED" || v == "PROVED-UNBOUNDED" || v == "PROVED-CERTIFIED" || v == "PROVED-ASSUMING" || v == "BOUNDED")
            return std::string("BOUNDED");
        return v;
    };
    // the headline is the `all` row; a run of coverage rows only has none
    const RowResult* head_p = &results.front();
    for (auto& r : results)
        if (r.row.name == "all") { head_p = &r; break; }
    const RowResult& head = *head_p;
    rep.verdict = module_verdict(head.verdict);
    rep.cls = head.cls;
    rep.message = head.message;
    rep.line = head.line;
    rep.counterexample = head.cex;
    rep.extra["pir_verdict_all"] = head.pir_verdict;
    std::ostringstream tbl;
    tbl << "  row                 pir verdict       module verdict   seconds  finding\n";
    std::vector<std::string> vacuous;
    for (auto& r : results) {
        if (r.row.cover) {
            const bool reach = r.verdict == "FAILED";
            const bool unreach = r.verdict == "PROVED" || r.verdict == "BOUNDED" || r.verdict == "PROVED-UNBOUNDED" ||
                                 r.verdict == "PROVED-ASSUMING" || r.verdict == "PROVED-CERTIFIED";
            char b[200];
            std::snprintf(b, sizeof b, "  %-19s %-17s %-16s %7.1f\n", r.row.name.c_str(), r.pir_verdict.c_str(),
                          reach ? "reachable" : unreach ? "UNREACHABLE" : r.verdict.c_str(), r.seconds);
            tbl << b;
            rep.extra["row." + r.row.name + ".pir"] = r.pir_verdict;
            rep.extra["row." + r.row.name + ".coverage"] = reach ? "reachable" : unreach ? "unreachable" : r.verdict;
            rep.extra["row." + r.row.name + ".seconds"] = std::to_string(r.seconds);
            if (unreach) vacuous.push_back(r.row.name.substr(6));
            rep.properties_checked.push_back(r.row.name + ": " + r.row.what);
            continue;
        }
        std::string tag = tag_of(r.message);
        std::string what = r.verdict != "FAILED" ? "" : (tag.empty() ? "native: " + r.cls : "module:" + tag);
        char buf[256];
        std::snprintf(buf, sizeof buf, "  %-19s %-17s %-16s %7.1f  %s\n", r.row.name.c_str(), r.pir_verdict.c_str(),
                      module_verdict(r.verdict).c_str(), r.seconds, what.c_str());
        tbl << buf;
        rep.extra["row." + r.row.name + ".pir"] = r.pir_verdict;
        rep.extra["row." + r.row.name + ".verdict"] = module_verdict(r.verdict);
        rep.extra["row." + r.row.name + ".seconds"] = std::to_string(r.seconds);
        if (!r.message.empty() && r.verdict == "FAILED") {
            rep.extra["row." + r.row.name + ".message"] = r.message;
            rep.extra["row." + r.row.name + ".line"] = r.line;
            rep.extra["row." + r.row.name + ".cex"] = r.cex;
        }
        rep.properties_checked.push_back(r.row.name + ": " + r.row.what);
    }
    rep.notes = tbl.str();
    if (!vacuous.empty()) {
        std::string v;
        for (auto& s : vacuous) v += (v.empty() ? "" : ", ") + s;
        rep.notes += "  VACUITY WARNING: not reachable under the model: " + v +
                     ". The verdicts above say nothing about those parts (a proof about code that never runs).\n";
        rep.extra["vacuity"] = v;
    }

    // level and assumptions
    // a device behind a ring (virtio) has no register window; its model is the hostile-queue stub
    const bool ring_model = !dev && std::find(sp.stubs.begin(), sp.stubs.end(), "virtio") != sp.stubs.end();
    const bool modelled = dev.has_value() || ring_model;
    rep.level = modelled ? "L4 (bounded)" : "L1 (bounded; no device model: every register read unconstrained)";
    if (rep.verdict == "FAILED" || rep.verdict == "UNKNOWN" || rep.verdict == "TIMEOUT" || rep.verdict == "NEEDS-HARNESS" ||
        rep.verdict == "NOTRUN" || rep.verdict == "ERROR")
        rep.level = "none (" + rep.verdict + ")";
    if (dev) {
        rep.assumptions.push_back("device model " + dev->name + " (" + dev->file + "), validation: " + dev->validation +
                                  (dev->validation_how.empty() ? "" : " - " + dev->validation_how));
        for (auto& s : dev->sources) rep.assumptions.push_back("device model source: " + s);
    } else if (ring_model) {
        rep.assumptions.push_back("device model: the virtqueue device is untrusted within the virtio ring protocol (src/prism/pir/models/device/linux_virtio.h), validation: unvalidated - reviewed by reading against include/uapi/linux/virtio_ring.h and drivers/virtio/virtio_ring.c; not run against a real host");
    } else {
        rep.assumptions.push_back("no device model: every register read is an arbitrary value of its width, writes have no effect, the interrupt line is arbitrary");
    }
    rep.assumptions.push_back("bounded sequences: probe, then at most " + std::to_string(sp.steps) +
                              " operations chosen from {" + [&] { std::string s; for (auto& o : sp.ops) s += (s.empty() ? "" : ", ") + o.name; return s; }() +
                              "}, then remove (docs/DEVICE_MODEL.md section 4)");
    rep.assumptions.push_back(std::string("events/interrupts may occur between steps") + (sp.irq_at_api ? " and at kernel API calls" : "") +
                              (sp.irq_at_mmio ? " and at every MMIO access" : "") + "; at most 2 interrupts and 2 device events per run; handler runs only while registered");
    rep.assumptions.push_back("kernel API stubs of the " + sp.kernel + " flavour (src/prism/pir/models/device/, a local stand-in for the R2 spec table): allocation, devm, irq, region and window operations may fail; locks, bit operations, logging and BUG/WARN as modelled there");
    rep.assumptions.push_back("devres resources are released in reverse order after remove or a failed probe; at most 6 devm resources and 2 locks");
    for (auto& a : sp.assumptions) rep.assumptions.push_back("module description: " + a);
    if (!patched_note.empty()) rep.assumptions.push_back("DRIVER SOURCE PATCHED: " + patched_note);
    rep.assumptions.push_back("the driver is compiled with the unit flags of " + (have_cdb ? opt.cc_like_file : std::string("the default flags")) +
                              " (front end drops flags that would define ISO C undefined behaviour, docs/PIR.md)");
    rep.assumptions.push_back("environment and bus setup (env/setup blocks of " + specpath.filename().string() + ") are hand-written C, reviewed by a person, not generated");
    // peak resident set: the largest of the rows' processes when they ran as children, else this process
    {
        long mx = 0;
        for (auto& r : results)
            if (auto it = r.extra.find("peak_rss_mb"); it != r.extra.end() && r.row.name.rfind("cover-", 0) != 0) mx = std::max(mx, std::atol(it->second.c_str()));
        if (mx > 0) rep.extra["peak_rss_mb_row_process"] = std::to_string(mx);
        for (auto& r : results)
            if (auto it = r.extra.find("peak_rss_mb"); it != r.extra.end()) rep.extra["row." + r.row.name + ".peak_rss_mb"] = it->second;
    }
    rep.seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
#ifdef __linux__
    struct rusage ru{};
    if (getrusage(RUSAGE_SELF, &ru) == 0) rep.extra["peak_rss_mb"] = std::to_string(ru.ru_maxrss / 1024);
#endif
    return rep;
}

