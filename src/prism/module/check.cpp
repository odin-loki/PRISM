// the module property named by a finding message "[module:<prop>] ..."
std::string tag_of(const std::string& msg) {
    auto a = msg.find("[module:");
    if (a == std::string::npos) return "";
    auto b = msg.find(']', a);
    if (b == std::string::npos) return "";
    return msg.substr(a + 8, b - a - 8);
}

nlohmann::json clone_entry(const nlohmann::json& tmpl, const fs::path& file, const fs::path& incdir) {
    nlohmann::json e = tmpl;
    std::string old = e.value("file", "");
    e["file"] = file.generic_string();
    auto swap_tok = [&](std::string t) { return t == old ? file.generic_string() : t; };
    if (e.contains("arguments")) {
        for (auto& a : e["arguments"]) {
            std::string s = a.get<std::string>();
            // drop the object output and the dependency flags that name another file
            a = swap_tok(s);
        }
        e["arguments"].push_back("-I" + incdir.generic_string());
    } else if (e.contains("command")) {
        std::string c = e["command"].get<std::string>();
        auto p = c.rfind(old);
        if (p != std::string::npos) c.replace(p, old.size(), file.generic_string());
        c += " -I" + incdir.generic_string();
        e["command"] = c;
    }
    return e;
}

