// Regenerate the loop-free lower_bound over libstdc++'s LP64 prime table in
// src/prism/pir/models/cxx/prism_hash_table.h (_M_next_bkt slow path).
//
// A symbolic index into the 304-entry table made Z3 blow up on every insert
// (unordered_map_contracts); this emits branches over groups of 16 primes and
// straight-line masks within a group. The primes are read from the header's
// own __prime_list (LP64 part). Rewrites the BEGIN/END generated block in place
// (idempotent). Build: c++ -std=c++20 -O1 gen_prime_lb.cpp -o gen_prime_lb
// Usage: gen_prime_lb <header>
#include <cstdio>
#include <fstream>
#include <regex>
#include <sstream>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc != 2) { std::fprintf(stderr, "usage: gen_prime_lb <header>\n"); return 2; }
    std::string s;
    { std::ifstream in(argv[1]); std::stringstream ss; ss << in.rdbuf(); s = ss.str(); }
    const auto a = s.find("__prime_list[] = {");
    if (a == std::string::npos) { std::fprintf(stderr, "no __prime_list\n"); return 1; }
    std::string blk = s.substr(a, s.find("};", a) - a);
    blk = std::regex_replace(blk, std::regex(R"(#if __SIZEOF_LONG__ != 8[\s\S]*?#else)"), "",
                             std::regex_constants::format_first_only);
    std::vector<unsigned long long> ps;
    std::regex num(R"((\d+)ul)");
    for (std::sregex_iterator it(blk.begin(), blk.end(), num), e; it != e && ps.size() < 304; ++it)
        ps.push_back(std::stoull((*it)[1]));
    if (ps.size() != 304 || ps[6] != 17) { std::fprintf(stderr, "bad table (%zu)\n", ps.size()); return 1; }
    const std::vector<unsigned long long> c(ps.begin() + 6, ps.begin() + 303);
    const std::string B = "        // BEGIN generated by tools/models/gen_prime_lb\n", E = "        // END generated\n";
    std::string out = B;
    out += "        // std::lower_bound(__prime_list + 6, __last_prime, __n) without a symbolic\n"
           "        // table index: branch on groups of 16 primes, masks keep the smallest\n"
           "        // prime >= __n within the group. Equal to lower_bound for every __n.\n"
           "        unsigned long __p, __m;\n";
    for (size_t i = 0; i < c.size(); i += 16) {
        const size_t n = std::min<size_t>(16, c.size() - i);
        const auto last = c[i + n - 1];
        out += "        " + std::string(i == 0 ? "if" : "else if") + " (__n <= " + std::to_string(last) + "ul) {\n";
        out += "            __p = " + std::to_string(last) + "ul;\n";
        for (size_t j = n - 1; j-- > 0;) {
            const auto q = std::to_string(c[i + j]);
            out += "            __m = 0ul - static_cast<unsigned long>(__n <= " + q + "ul); __p = (__p & ~__m) | (" + q + "ul & __m);\n";
        }
        out += "        }\n";
    }
    out += "        else { _M_next_resize = size_t(-1); return " + std::to_string(ps[303]) + "ul; }\n";
    out += "        _M_next_resize = _M_floor_scaled(__p);\n        return __p;\n" + E;
    auto b = s.find("        // BEGIN generated by tools/models/gen_prime_lb");
    if (b == std::string::npos) { std::fprintf(stderr, "no generated block\n"); return 1; }
    const auto e = s.find(E, b);
    s = s.substr(0, b) + out + s.substr(e + E.size());
    std::ofstream(argv[1]) << s;
    return 0;
}
