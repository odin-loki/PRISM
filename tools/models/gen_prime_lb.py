#!/usr/bin/env python3
"""Regenerate the loop-free lower_bound over libstdc++'s LP64 prime table in
src/prism/pir/models/cxx/prism_hash_table.h (_M_next_bkt slow path).

A symbolic index into the 304-entry table made Z3 blow up on every insert
(unordered_map_contracts); this emits branches over groups of 16 primes and
straight-line masks within a group. Usage: gen_prime_lb.py <header> (in place).
The primes are read from the header's own __prime_list (LP64 part)."""
import re, sys

p = sys.argv[1]
s = open(p).read()
a = s.index("__prime_list[] = {")
blk = s[a:s.index("};", a)]
blk = re.sub(r"#if __SIZEOF_LONG__ != 8.*?#else", "", blk, flags=re.S).replace("#endif", "")
ps = [int(x) for x in re.findall(r"(\d+)ul", blk)][:304]
assert len(ps) == 304 and ps[6] == 17, (len(ps), ps[:8])
c = ps[6:303]
B, E = "        // BEGIN generated by tools/models/gen_prime_lb.py\n", "        // END generated\n"
L = ["        // std::lower_bound(__prime_list + 6, __last_prime, __n) without a symbolic",
     "        // table index: branch on groups of 16 primes, masks keep the smallest",
     "        // prime >= __n within the group. Equal to lower_bound for every __n.",
     "        unsigned long __p, __m;"]
for i in range(0, len(c), 16):
    g = c[i:i + 16]
    L.append(f"        {'if' if i == 0 else 'else if'} (__n <= {g[-1]}ul) {{")
    L.append(f"            __p = {g[-1]}ul;")
    for q in reversed(g[:-1]):
        L.append(f"            __m = 0ul - static_cast<unsigned long>(__n <= {q}ul); __p = (__p & ~__m) | ({q}ul & __m);")
    L.append("        }")
L.append(f"        else {{ _M_next_resize = size_t(-1); return {ps[303]}ul; }}")
L += ["        _M_next_resize = _M_floor_scaled(__p);", "        return __p;"]
new = B + "\n".join(L) + "\n" + E
if B in s:
    s = s[:s.index(B)] + new + s[s.index(E) + len(E):]
else:
    old_a = s.index("        const unsigned long* __prime_list = _S_prime_list();\n#if __SIZEOF_LONG__ == 8")
    old_b = s.index("        return *__next_bkt;\n", old_a) + len("        return *__next_bkt;\n")
    old = s[old_a:old_b]
    old32 = old.replace("#if __SIZEOF_LONG__ == 8\n        constexpr size_t __n_primes = 256 + 48;\n#else\n", "").replace("#endif\n", "", 1)
    s = s[:old_a] + "#if __SIZEOF_LONG__ == 8\n" + new + "#else\n" + old32 + "#endif\n" + s[old_b:]
open(p, "w").write(s)
